#!/usr/bin/env bash
# Renders the component set every Talos cluster starts with into
# components/: Cilium from its chart, the CRD of Cilium's cluster-wide policy
# from Cilium's source, and Argo CD, Kyverno and the local path provisioner
# from their charts. It renders the hosting set's six charts too: OpenBao,
# cert-manager, trust-manager, External Secrets, Sealed Secrets and Traefik.
# With --check it fails when a committed file differs from a fresh render or
# names an image by anything but a digest.
# Usage: scripts/render-components.sh [--check]
#   HELM names the helm binary, helm on PATH by default; CI pins v3.18.6.
# It exists so the manifests a node applies are reviewable bytes that come
# from one pinned chart or file, each checked against a published sha256.
set -euo pipefail

readonly cilium_version=1.19.9
readonly cilium_chart_sha256=b54b1bae91bd87bcf9f19672e7f23304156697596332e6c64a53b62143b2b251
readonly cilium_chart_url="https://helm.cilium.io/cilium-${cilium_version}.tgz"
readonly cilium_crd_sha256=ae742b7ad66ddb4af752b6ae9787f2d3bc4597e3f29df80417967767f9bf2a79
readonly cilium_crd_url="https://raw.githubusercontent.com/cilium/cilium/v${cilium_version}/pkg/k8s/apis/cilium.io/client/crds/v2/ciliumclusterwidenetworkpolicies.yaml"

readonly argocd_chart_version=10.10.5
readonly argocd_chart_sha256=ba6447eeed42bc41d1f0527721047b236304e97669a7b6286d02be4a1644ba7a
readonly argocd_chart_url="https://github.com/argoproj/argo-helm/releases/download/argo-cd-${argocd_chart_version}/argo-cd-${argocd_chart_version}.tgz"

readonly kyverno_chart_version=3.9.1
readonly kyverno_chart_sha256=7b7fe51a431b5b133b0ce7eb9dcb222b6a37fb967c163223cf480054ad14d752
readonly kyverno_chart_url="https://kyverno.github.io/kyverno/kyverno-${kyverno_chart_version}.tgz"

# The project publishes no chart repository, so the chart comes from the source archive of the commit its v0.0.37 tag
# names, whose contents GitHub keeps the same for a commit id.
readonly local_path_version=0.0.37
readonly local_path_commit=49b2be8e26d6d34c9afaa21fa33108d2e82f8955
readonly local_path_archive_sha256=2b95efae90cd01de97dd9809739d24b0ad2ccaded6e86e308f71733b690b3de8
readonly local_path_archive_url="https://github.com/rancher/local-path-provisioner/archive/${local_path_commit}.tar.gz"

# Each hosting chart is name, version, the sha256 its repository's index.yaml publishes, URL, namespace, and whether
# the render creates that namespace.
readonly hosting_charts=(
  "openbao 0.30.2 53a55a9e53e28656b8d4b1264a549116267391eb2652735a855cd94fec461c9f https://github.com/openbao/openbao-helm/releases/download/openbao-0.30.2/openbao-0.30.2.tgz openbao create"
  "cert-manager v1.21.2 73a56e1728edd6c99f1f31082618c3259d279a76b7ebd3d4bdc5475c2442d34a https://charts.jetstack.io/charts/cert-manager-v1.21.2.tgz cert-manager create"
  "trust-manager v0.25.0 b271163e34fdf5c0894e56e568f3616c0db3a02d7ea5a8f9bcfd42f9f3e111f0 https://charts.jetstack.io/charts/trust-manager-v0.25.0.tgz cert-manager -"
  "external-secrets 2.11.0 8199b42fe80b871c6a86233a80bb14f599fd6e1e6462c1216d836577f845e161 https://github.com/external-secrets/external-secrets/releases/download/helm-chart-2.11.0/external-secrets-2.11.0.tgz external-secrets create"
  "sealed-secrets 2.20.0 6092d219c697f3c9ae3a386ba24bfdd86877c5e2fc8892e2af8a810145b990ef https://github.com/bitnami/sealed-secrets/releases/download/helm-v2.20.0/sealed-secrets-2.20.0.tgz kube-system -"
  "traefik 41.6.1 1e65d46bae0ba0baef460a1d82686b50f156372865a3d7d8a85b51c3855b2ef9 https://traefik.github.io/charts/traefik/traefik-41.6.1.tgz traefik create"
)

root=$(cd "$(dirname "$0")/.." && pwd)
readonly root
# shellcheck source=tools/tools.env
. "$root/tools/tools.env"
# The kube version the charts' capability checks see, the release tools.env pins.
readonly kube_version=${KUBERNETES_VERSION#v}
# shellcheck source=scripts/lib/digests.sh
. "$root/scripts/lib/digests.sh"
helm=${HELM:-helm}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

usage() {
  echo "usage: $0 [--check]" >&2
  exit 2
}

# fetch <url> <sha256> <dest> downloads a file and refuses it unless it has the pinned sha256.
fetch() {
  curl -fsSL --proto '=https' -o "$3" "$1"
  echo "$2  $3" | sha256sum -c --quiet -
}

# header <source> prints the two lines that open every rendered file.
header() {
  printf '# Generated by scripts/render-components.sh from %s.\n' "$1"
  printf '# Edit components/render/ or the script and render again, never this file.\n'
}

render_cilium() {
  fetch "$cilium_chart_url" "$cilium_chart_sha256" "$work/cilium.tgz"
  {
    header "the cilium ${cilium_version} chart"
    "$helm" template cilium "$work/cilium.tgz" \
      --namespace kube-system \
      --kube-version "$kube_version" \
      --values "$root/components/render/cilium-values.yaml"
  } > "$work/cilium.yaml"
}

render_cilium_crd() {
  fetch "$cilium_crd_url" "$cilium_crd_sha256" "$work/crd.yaml"
  {
    header "Cilium v${cilium_version}'s CiliumClusterwideNetworkPolicy CRD"
    cat "$work/crd.yaml"
  } > "$work/policy-crd.yaml"
}

# render_argocd prepends the namespace, since the chart creates none.
render_argocd() {
  fetch "$argocd_chart_url" "$argocd_chart_sha256" "$work/argocd.tgz"
  {
    header "the argo-cd ${argocd_chart_version} chart"
    printf -- '---\napiVersion: v1\nkind: Namespace\nmetadata:\n  name: argocd\n'
    "$helm" template argocd "$work/argocd.tgz" \
      --namespace argocd \
      --kube-version "$kube_version" \
      --values "$root/components/render/argocd-values.yaml"
  } > "$work/argocd.yaml"
}

# render_kyverno prepends the namespace, since the chart creates none, and
# leaves out the chart's tests, which pull an image by tag alone.
render_kyverno() {
  fetch "$kyverno_chart_url" "$kyverno_chart_sha256" "$work/kyverno.tgz"
  {
    header "the kyverno ${kyverno_chart_version} chart"
    printf -- '---\napiVersion: v1\nkind: Namespace\nmetadata:\n  name: kyverno\n'
    "$helm" template kyverno "$work/kyverno.tgz" \
      --namespace kyverno \
      --kube-version "$kube_version" \
      --skip-tests \
      --values "$root/components/render/kyverno-values.yaml"
  } > "$work/kyverno.yaml"
}

render_local_path() {
  local chart="local-path-provisioner-${local_path_commit}/deploy/chart/local-path-provisioner"
  fetch "$local_path_archive_url" "$local_path_archive_sha256" "$work/local-path-provisioner.tar.gz"
  tar -xzf "$work/local-path-provisioner.tar.gz" -C "$work" "$chart"
  {
    header "the local-path-provisioner ${local_path_version} chart"
    "$helm" template local-path-provisioner "$work/$chart" \
      --namespace local-path-storage \
      --kube-version "$kube_version" \
      --values "$root/components/render/local-path-provisioner-values.yaml"
  } > "$work/local-path-provisioner.yaml"
}

# render_hosting_chart <name> <version> <sha256> <url> <namespace> <create|-> renders one hosting chart with the CRDs in
# its crds/ folder, which helm template leaves out by default, and without its tests, which Talos would run as
# ordinary pods.
render_hosting_chart() {
  fetch "$4" "$3" "$work/$1.tgz"
  {
    header "the $1 $2 chart"
    if [ "$6" = create ]; then
      printf -- '---\napiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n' "$5"
    fi
    "$helm" template "$1" "$work/$1.tgz" \
      --include-crds \
      --namespace "$5" \
      --kube-version "$kube_version" \
      --skip-tests \
      --values "$root/components/render/$1-values.yaml"
  } > "$work/$1.yaml"
}

# compare <fresh> <committed> fails when the committed file differs from the fresh render.
compare() {
  if ! diff -q "$2" "$1" > /dev/null; then
    echo "render-components: $2 differs from a fresh render; run scripts/render-components.sh and commit the result" >&2
    return 1
  fi
  echo "render-components: $2 matches a fresh render"
}

main() {
  local check=false
  case ${1-} in
    "") ;;
    --check) check=true ;;
    *) usage ;;
  esac

  render_cilium
  render_cilium_crd
  render_argocd
  render_kyverno
  render_local_path
  refuse_undigested "$work/cilium.yaml" render-components
  refuse_undigested "$work/argocd.yaml" render-components
  refuse_undigested "$work/kyverno.yaml" render-components
  refuse_undigested "$work/local-path-provisioner.yaml" render-components

  local pairs=("cilium.yaml:components/cilium/cilium.yaml" "policy-crd.yaml:components/cilium/policy-crd.yaml" "argocd.yaml:components/argocd/argocd.yaml" "kyverno.yaml:components/kyverno/kyverno.yaml" "local-path-provisioner.yaml:components/local-path-provisioner/local-path-provisioner.yaml")
  local chart name version sha256 url namespace create
  for chart in "${hosting_charts[@]}"; do
    read -r name version sha256 url namespace create <<< "$chart"
    render_hosting_chart "$name" "$version" "$sha256" "$url" "$namespace" "$create"
    refuse_undigested "$work/$name.yaml" render-components
    pairs+=("$name.yaml:components/$name/$name.yaml")
  done
  local pair failed=0
  for pair in "${pairs[@]}"; do
    if $check; then
      compare "$work/${pair%%:*}" "$root/${pair#*:}" || failed=1
    else
      cp "$work/${pair%%:*}" "$root/${pair#*:}"
      echo "render-components: wrote ${pair#*:}"
    fi
  done
  return "$failed"
}

main "$@"
